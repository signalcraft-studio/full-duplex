"""Precompute the home-page dot globe from world-atlas (assets/vendor/countries-110m.json) and
data/tracker.json. Writes assets/globe-dots.json. Imported by scripts/build.py; standard library only."""
import json, math, pathlib

def decode(topo):
    sx, sy = topo['transform']['scale']; tx, ty = topo['transform']['translate']
    arcs = []
    for arc in topo['arcs']:
        x = y = 0; pts = []
        for dx, dy in arc:
            x += dx; y += dy; pts.append((x * sx + tx, y * sy + ty))
        arcs.append(pts)
    def ring(idx):
        out = []
        for i in idx:
            pts = arcs[i] if i >= 0 else arcs[~i][::-1]
            out.extend(pts if not out else pts[1:])
        return out
    feats = {}
    for g in topo['objects']['countries']['geometries']:
        if g.get('type') == 'Polygon': polys = [[ring(r) for r in g['arcs']]]
        elif g.get('type') == 'MultiPolygon': polys = [[ring(r) for r in p] for p in g['arcs']]
        else: continue
        feats[g.get('id')] = polys
    return feats

def inside(lon, lat, polys):
    for rings in polys:
        c = False
        for r in rings:
            n = len(r); j = n - 1
            for i in range(n):
                xi, yi = r[i]; xj, yj = r[j]
                if (yi > lat) != (yj > lat) and lon < (xj - xi) * (lat - yi) / (yj - yi) + xi: c = not c
                j = i
        if c: return True
    return False

def build(root, step=1.5):
    topo = json.loads((root / 'assets/vendor/countries-110m.json').read_text())
    rows = json.loads((root / 'data/tracker.json').read_text())['rows']
    rank = {'announced': 1, 'trial': 2, 'live': 3}; status = {}
    for r in rows:
        if r['iso_n3']: status[r['iso_n3']] = max(status.get(r['iso_n3'], 0), rank[r['status']])
    feats = {k: v for k, v in decode(topo).items() if k != '010'}
    bbox = {}
    for k, polys in feats.items():
        xs = [p[0] for rs in polys for r in rs for p in r]; ys = [p[1] for rs in polys for r in rs for p in r]
        bbox[k] = (min(xs), min(ys), max(xs), max(ys))
    pts = []; cent = {}
    lat = -90 + step / 2
    while lat < 90:
        n = max(1, int(round(360 * math.cos(math.radians(lat)) / step)))
        for i in range(n):
            lon = -180 + (i + .5) * 360 / n
            for k, (a, b, c, d) in bbox.items():
                if a <= lon <= c and b <= lat <= d and inside(lon, lat, feats[k]):
                    s = status.get(k, 0); pts += [round(lat * 10), round(lon * 10), s]
                    if s == 3: cent.setdefault(k, []).append((lat, lon))
                    break
        lat += step
    # centroids of live countries (3D mean), used for illustrative satellite-pass arcs
    cs = []
    for k, ll in sorted(cent.items(), key=lambda kv: -len(kv[1])):
        x = sum(math.cos(math.radians(a)) * math.cos(math.radians(o)) for a, o in ll); y = sum(math.cos(math.radians(a)) * math.sin(math.radians(o)) for a, o in ll); z = sum(math.sin(math.radians(a)) for a, o in ll)
        cs.append([round(math.degrees(math.atan2(z, math.hypot(x, y))), 1), round(math.degrees(math.atan2(y, x)), 1)])
    (root / 'assets/globe-dots.json').write_text(json.dumps({'note': 'Generated by scripts/globe_dots.py: [lat*10, lon*10, status] (0 none, 1 announced, 2 trial, 3 live)', 'p': pts, 'live': cs}, separators=(',', ':')) + '\n')
    return len(pts) // 3

if __name__ == '__main__':
    print(build(pathlib.Path(__file__).resolve().parent.parent), 'dots')
